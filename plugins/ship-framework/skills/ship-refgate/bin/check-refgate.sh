#!/usr/bin/env bash
# Ship Framework — design gate (PreToolUse on Edit|Write)
#
# Preventive: it runs BEFORE Edit/Write and can refuse them. Shell commands (sed -i, scripts,
# heredocs) don't pass through it — check-after-shell.sh re-applies these rules after each Bash
# call and reports what slipped through (detection, not prevention).
#
# One job: new UI shouldn't be invented before the product has a design contract
# (PDC.md → DESIGN.md, design-model.yaml, design/components.yaml). So:
#   - Ship project, no PDC.md, the edit CREATES a UI/motion/copy file → deny, with the
#     on-ramp (/shipmate design: adopt the existing system, or plant a seed).
#   - Everything else → allow: edits to existing files (a one-line fix in an existing app
#     is never locked out), logic/test files, design files themselves, non-Ship projects.
# No reading receipts or marker files — review judges outcomes (FRICTION-LOG #8).
#
# Output (single line): allow → {}   deny → {"hookSpecificOutput":{...,"permissionDecision":"deny",...}}
# Input: hook JSON on stdin with tool_input.file_path. Fails open on anything unexpected.

set -uo pipefail

ROOT="${CLAUDE_PROJECT_DIR:-.}"
cd "$ROOT" 2>/dev/null || { echo '{}'; exit 0; }
ROOT="$(pwd -P)"

allow() { echo '{}'; exit 0; }
deny() {
  printf '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"%s"}}\n' "$1"
  exit 0
}

INPUT="$(cat 2>/dev/null || true)"
FILE_PATH="$(printf '%s' "$INPUT" | grep -o '"file_path"[[:space:]]*:[[:space:]]*"[^"]*"' | head -1 \
             | sed 's/.*"file_path"[[:space:]]*:[[:space:]]*"//; s/"$//' || true)"
[ -n "$FILE_PATH" ] || allow

# Generated files (Theme.swift, tokens.css, Theme.kt, COMPONENTS.md…) are rebuilt from
# design-model.yaml — a hand edit would be silently lost on the next emit.
if [ -f "$FILE_PATH" ] && head -5 "$FILE_PATH" 2>/dev/null | grep -q "Generated by Ship\|ship-generated:"; then
  deny "Design gate: this file is generated from design-model.yaml — hand edits are lost on the next emit. Change design-model.yaml (or design/components.yaml), then re-emit with the command in PDC.md."
fi
# (The header marks the file itself, so this holds in any project — with or without Ship's CLAUDE.md.)

# New-UI rule: Ship projects only — the plugin registers this hook everywhere. Same detection as setup.sh.
grep -q "## /team\|## Ship Framework\|ship-framework" CLAUDE.md 2>/dev/null || allow


# The contract exists → nothing to gate. Existing file → never locked out.
[ -f PDC.md ] && allow
[ -e "$FILE_PATH" ] && [ -z "${REFGATE_ASSUME_NEW:-}" ] && allow   # check-after-shell asks about files a command just created

# Classify by the path inside the project (a project folder named "motion" isn't motion).
case "$FILE_PATH" in
  "$ROOT"/*) REL="${FILE_PATH#"$ROOT"/}" ;;
  /*)        REL="$FILE_PATH" ;;
  *)         REL="${FILE_PATH#./}" ;;
esac
REL="/$REL"

case "$REL" in
  # Design contract + Ship memory files are how you get out of the gate — never blocked.
  */DESIGN.md|*/PDC.md|*/design/*|*/design-model.yaml|*/design-model.draft.yaml|*/.claude/*|*/.ship/*|\
  */LEARNINGS.md|*/DECISIONS.md|*/TASKS.md|*/CONTEXT.md|*/CLAUDE.md|*/AGENTS.md|*/README.md)
    allow ;;
  # Tests, logic, config, data — not design surfaces.
  */test/*|*/tests/*|*/__tests__/*|*Tests/*|*_test.*|*.test.*|*.spec.*|\
  */models/*|*/Models/*|*/services/*|*/Services/*|*/utils/*|*/Utils/*|*/lib/*|*/helpers/*|\
  */api/*|*/API/*|*/store/*|*/Store/*|*/hooks/*|*/middleware/*|\
  *.json|*.yaml|*.yml|*.toml|*.plist|*.xcconfig|*.pbxproj|*.sh|*.py|*.md|*.txt|*.lock|*.gitignore)
    allow ;;
esac

if [ -f DESIGN.md ]; then
  deny "Design gate: new UI in a Ship project needs the design contract. DESIGN.md exists but PDC.md doesn't — offer the design stage now (/shipmate design indexes what you have; ~2 minutes). Editing existing files is not blocked."
elif ls ./*.xcodeproj ./package.json ./src ./app ./App ./Sources >/dev/null 2>&1; then
  deny "Design gate: new UI in a Ship project needs the design contract. This looks like an existing app — offer the design stage now (/shipmate design adopts its current design system; keeps your names; views unchanged). Editing existing files is not blocked."
else
  deny "Design gate: new UI in a Ship project needs the design contract. Offer the design stage now (/shipmate design plants a small seed: core tokens, a few components — about 2 minutes). Editing existing files is not blocked."
fi
