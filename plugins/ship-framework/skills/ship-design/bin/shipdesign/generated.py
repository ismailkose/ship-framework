"""Generated-file contract: header + content hash, refuse-to-clobber writes, --check.

Every file Ship generates starts with a few comment lines ending in a marker:

    // ship-generated: ship-design/2.0.0 target=swiftui sha256=<16 hex of the body>

The body is everything after the marker line. On re-emit:

- target missing                    → write it
- no marker (hand-written file)     → refuse unless --force
- old Ship header without a hash    → refuse unless --force (can't rule out hand edits); if its
                                      body already equals the new output, just add the header
- marker, body hash ≠ recorded hash → hand-edited → refuse unless --force
- marker, body == new body          → unchanged (no churn)
- otherwise                         → overwrite

Refusals print a unified diff of what would change. `--check` never writes; any state other
than "current" is a failure (exit 1), so it can gate review and CI.
"""

import difflib
import hashlib
import re

GENERATOR = "ship-design"
VERSION = "2.0.0"
MARK = "ship-generated:"
LEGACY_MARK = "Generated by Ship from design-model.yaml"
COMMENT = {
    "swift": ("// ", ""), "kt": ("// ", ""), "css": ("/* ", " */"),
    "html": ("<!-- ", " -->"), "md": ("<!-- ", " -->"), "yaml": ("# ", ""),
}
MARK_RE = re.compile(r"ship-generated:\s*(\S+)\s+target=(\S+)\s+sha256=([0-9a-f]{16})")


def body_hash(body):
    return hashlib.sha256(body.encode("utf-8")).hexdigest()[:16]


def render(style, target, human_lines, body, lead=()):
    """Header (human lines + marker) followed by the body. `lead` lines go first (a DESIGN.md
    export must open with its `---` front-matter fence, so its header is YAML comments)."""
    pre, post = COMMENT[style]
    lines = list(lead) + [f"{pre}{line}{post}".rstrip() for line in human_lines]
    lines.append(f"{pre}{MARK} {GENERATOR}/{VERSION} target={target} sha256={body_hash(body)}{post}")
    return "\n".join(lines) + "\n" + body


def parse(text):
    """→ dict(marker=bool, legacy=bool, recorded=hash|None, body=str, version=str|None)."""
    lines = text.split("\n")
    for i, line in enumerate(lines[:20]):
        m = MARK_RE.search(line)
        if m:
            return {"marker": True, "legacy": False, "version": m.group(1), "target": m.group(2),
                    "recorded": m.group(3), "body": "\n".join(lines[i + 1:])}
    legacy = any(LEGACY_MARK in line for line in lines[:5])
    return {"marker": False, "legacy": legacy, "version": None, "target": None, "recorded": None, "body": text}


def strip_leading_comments(text):
    lines = text.split("\n")
    i = 0
    while i < len(lines) and (lines[i].startswith("//") or not lines[i].strip()):
        i += 1
    return "\n".join(lines[i:])


def diff(old, new, path, limit=80):
    d = list(difflib.unified_diff(old.splitlines(), new.splitlines(), f"{path} (on disk)",
                                  f"{path} (from design-model.yaml)", lineterm="", n=1))
    if len(d) > limit:
        d = d[:limit] + [f"… {len(d) - limit} more diff lines"]
    return "\n".join(d)


def state(path, new_text):
    """Classify the target against freshly generated text.

    → (state, detail) with state in: missing | current | stale | handwritten | edited | legacy | legacy-current
    """
    if not path.exists():
        return "missing", ""
    old = path.read_text(encoding="utf-8")
    new_body = parse(new_text)["body"]
    info = parse(old)
    if not info["marker"]:
        if info["legacy"]:
            if strip_leading_comments(old).strip() == strip_leading_comments(new_body).strip():
                return "legacy-current", ""
            return "legacy", diff(old, new_text, path.name)
        return "handwritten", diff(old, new_text, path.name)
    if body_hash(info["body"]) != info["recorded"]:
        return "edited", diff(old, new_text, path.name)
    if info["body"] == new_body:
        return "current", ""
    return "stale", diff(old, new_text, path.name)


MESSAGES = {
    "missing": "not generated yet",
    "current": "up to date",
    "legacy-current": "matches the model (old header without a hash — re-emit to add one)",
    "stale": "stale — design-model.yaml changed since it was generated",
    "legacy": "was generated by an older Ship without a content hash, so hand edits can't be ruled out "
              "— review the diff, then re-emit once with --force",
    "handwritten": "exists but was not generated by Ship (no ship-generated header) — refusing to overwrite",
    "edited": "was edited by hand after generation (hash mismatch) — refusing to overwrite",
}


def write(path, new_text, force=False, check=False, dry_run=False):
    """Apply the contract. → (ok: bool, state, message, diff_text)."""
    st, d = state(path, new_text)
    if check:
        ok = st in ("current", "legacy-current")
        return ok, st, MESSAGES[st], d
    if st == "current":
        return True, st, "unchanged", ""
    if st == "legacy-current" and not dry_run:
        path.write_text(new_text, encoding="utf-8")
        return True, st, "header upgraded (content unchanged)", ""
    if st in ("handwritten", "edited", "legacy") and not force:
        return False, st, MESSAGES[st] + " (re-run with --force to replace it)", d
    if dry_run:
        return True, st, "would write", d
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(new_text, encoding="utf-8")
    verb = {"missing": "created", "handwritten": "replaced (--force)", "edited": "replaced (--force)",
            "legacy": "replaced (--force)"}.get(st, "updated")
    return True, st, verb, d
