#!/usr/bin/env python3
"""Ship design registry tool — validate, emit, match, adopt, audit, document.

    design_model.py validate      [--root DIR] [--json]
    design_model.py emit TARGET…  [--out PATH] [--check] [--force] [--dry-run]
                                  TARGET: swiftui css tailwind compose preview-swiftui preview-html all
    design_model.py emit-swiftui  [--out PATH] …   (also emit-css, emit-tailwind, emit-compose)
    design_model.py check         (validate + every generated file current; for review / CI)
    design_model.py status        [--json]         planned vs realized components, variant checks
    design_model.py match --role R [--variant V] [--tokens a,b] [--context TEXT] [--json]
    design_model.py extend --component NAME [--variant V] [--param P…] [--tokens a,b] [--changes-existing]
    design_model.py adopt         [--platform auto|swiftui|web] [--exclude GLOB…] [--force] [--json]
    design_model.py audit         [--model PATH] [--exclude GLOB…] [--strict] [--json]
    design_model.py docs          [--out PATH] [--check] [--force]
    design_model.py render        [--out PNG] [--scheme light|dark|both] [--width PT]
    design_model.py emit-designmd [--out PATH] [--check] [--force]   (optional interop, off by default)

Deterministic on purpose: the registry check in /shipmate build must be a file read, not inference.
Stdlib only (Python 3.9+). Exit codes: 0 ok · 1 invalid / stale / refused / miss / needs founder ·
2 usage. Schema + ownership: ../references/design-model-schema.md
"""

import sys

sys.dont_write_bytecode = True  # never leave __pycache__ inside an installed skill

import argparse  # noqa: E402
import json  # noqa: E402
from pathlib import Path  # noqa: E402

sys.path.insert(0, str(Path(__file__).resolve().parent))

from shipdesign import generated  # noqa: E402
from shipdesign.yamlsub import YamlError, dump_yaml, load_yaml  # noqa: E402,F401  (load_yaml: provenance-check imports it)
from shipdesign.registry import (DESIGNMD_DEFAULT, DOCS_DEFAULT, EMIT_TARGETS, emit_config,  # noqa: E402
                                 emit_out, load_registry, validate)
from shipdesign.emit_swiftui import emit_swiftui  # noqa: E402,F401  (kept importable)

TARGET_STYLE = {"swiftui": "swift", "css": "css", "tailwind": "css", "compose": "kt",
                "preview-swiftui": "swift", "preview-html": "html"}


def rel(path, root):
    try:
        return str(Path(path).resolve().relative_to(root))
    except ValueError:
        return str(path)


def header_lines(model, target):
    brand = (model.get("brand") or {}).get("name", "")
    lines = ["Generated by Ship from design-model.yaml — do not edit by hand.",
             "Change design-model.yaml, then re-emit (the command for this project is in PDC.md)."]
    if target == "tailwind":
        lines.append("Tailwind v4: @import this file after `@import \"tailwindcss\";`.")
    if target in ("preview-swiftui", "preview-html"):
        lines.append("Also mirrors design/components.yaml.")
    lines.append(f"Brand: {brand}")
    return lines


def build(target, model, comps, root):
    from shipdesign import emit_compose, emit_web, preview
    body = {
        "swiftui": lambda: emit_swiftui(model),
        "css": lambda: emit_web.emit_css(model),
        "tailwind": lambda: emit_web.emit_tailwind(model, root),
        "compose": lambda: emit_compose.emit_compose(model),
        "preview-swiftui": lambda: preview.emit_preview_swiftui(model, comps),
        "preview-html": lambda: preview.emit_preview_html(model, comps),
    }[target]()
    return generated.render(TARGET_STYLE[target], target, header_lines(model, target), body)


def out_path(root, arg):
    p = Path(arg)
    return p if p.is_absolute() else root / p


def report_write(path, root, ok, st, msg, d, show_diff=True):
    mark = "✓" if ok else "✗"
    stream = sys.stdout if ok else sys.stderr
    print(f"{mark} {rel(path, root)}: {msg}", file=stream)
    if d and (not ok or show_diff) and st not in ("missing",):
        print(d, file=stream)


def require_valid(root, quiet=False):
    errors, warnings = validate(root)
    if not quiet:
        for w in warnings:
            print(f"warn: {w}")
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        print(f"✗ design registry invalid ({len(errors)} errors)", file=sys.stderr)
        return False
    return True


# ── commands ─────────────────────────────────────────────────────────────────

def cmd_validate(args, root):
    errors, warnings = validate(root)
    if args.json:
        print(json.dumps({"valid": not errors, "errors": errors, "warnings": warnings}, indent=2))
        return 1 if errors else 0
    for w in warnings:
        print(f"warn: {w}")
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        print(f"✗ design registry invalid ({len(errors)} errors)", file=sys.stderr)
        return 1
    print("✓ design registry valid")
    return 0


def configured_targets(model):
    return [t for t in EMIT_TARGETS if emit_config(model, t).get("out")]


def cmd_emit(args, root, targets):
    if not require_valid(root, quiet=args.check):
        return 1
    model, comps = load_registry(root)
    if "all" in targets:
        targets = configured_targets(model)
        if not targets:
            print("✗ `emit all` emits the targets that have emit.<target>.out in design-model.yaml — none are set",
                  file=sys.stderr)
            return 1
    if args.out and len(targets) > 1:
        print("✗ --out works with one target at a time", file=sys.stderr)
        return 2
    status = 0
    for t in targets:
        path = out_path(root, args.out or emit_out(model, t))
        ok, st, msg, d = generated.write(path, build(t, model, comps, root), force=args.force,
                                         check=args.check, dry_run=args.dry_run)
        report_write(path, root, ok, st, msg, d, show_diff=args.dry_run)
        status |= 0 if ok else 1
    return status


def cmd_check(args, root):
    errors, _ = validate(root)
    if errors:
        for e in errors:
            print(f"error: {e}", file=sys.stderr)
        print(f"✗ design registry invalid ({len(errors)} errors)", file=sys.stderr)
        return 1
    model, comps = load_registry(root)
    status = 0
    results = []
    for t in configured_targets(model):
        path = out_path(root, emit_out(model, t))
        ok, st, msg, _ = generated.write(path, build(t, model, comps, root), check=True)
        results.append((t, rel(path, root), ok, msg))
        status |= 0 if ok else 1
    docs = out_path(root, emit_config(model, "docs").get("out") or DOCS_DEFAULT)
    if docs.exists() or emit_config(model, "docs").get("out"):
        ok, st, msg, _ = generated.write(docs, build_docs(model, comps, root), check=True)
        results.append(("docs", rel(docs, root), ok, msg))
        status |= 0 if ok else 1
    dmd = emit_config(model, "designmd").get("out")
    if dmd:
        ok, st, msg, _ = generated.write(out_path(root, dmd), build_designmd(model, comps), check=True)
        results.append(("designmd", dmd, ok, msg))
        status |= 0 if ok else 1
    for t, p, ok, msg in results:
        print(f"{'✓' if ok else '✗'} {t:16} {p}: {msg}")
    if not results:
        print("✓ registry valid — no generated outputs configured (set emit.<target>.out to track them)")
    elif status:
        print("✗ generated files are out of date — re-emit (never hand-edit generated files)", file=sys.stderr)
    return status


def cmd_status(args, root):
    from shipdesign.components import status
    try:
        _model, comps = load_registry(root)
    except YamlError as exc:
        print(f"✗ {exc}", file=sys.stderr)
        return 1
    rows = status(root, comps)
    if args.json:
        print(json.dumps({"components": rows,
                          "counts": {s: sum(1 for r in rows if r["state"] == s) for s in ("realized", "planned", "broken")}},
                         indent=2))
    else:
        for state in ("realized", "planned", "broken"):
            group = [r for r in rows if r["state"] == state]
            print(f"{state} ({len(group)})")
            for r in group:
                extra = f"  variants: {', '.join(r['variants'])}" if r["variants"] else ""
                print(f"  {r['name']:24} {r['role'] or '(no role)':16} {r['file'] or '—'}{extra}")
                for v in r["missing_variants"]:
                    print(f"      warn: variant '{v}' not found in {r['file']}")
    return 1 if any(r["state"] == "broken" for r in rows) else 0


def split_tokens(s):
    return [t.strip() for t in (s or "").split(",") if t.strip()]


def cmd_match(args, root):
    from shipdesign.components import format_match, match
    try:
        model, comps = load_registry(root)
    except YamlError as exc:
        print(f"✗ {exc}", file=sys.stderr)
        return 1
    results = match(model, comps, role=args.role, variant=args.variant, tokens=split_tokens(args.tokens),
                    context=args.context)
    need = f"role={args.role}" + (f" variant={args.variant}" if args.variant else "") + \
           (f" tokens={args.tokens}" if args.tokens else "")
    usable = [r for r in results if r["verdict"] in ("reuse", "extend", "planned")]
    if args.json:
        print(json.dumps({"need": {"role": args.role, "variant": args.variant, "tokens": split_tokens(args.tokens),
                                   "context": args.context},
                          "hit": bool(usable), "best": usable[0]["name"] if usable else None,
                          "candidates": results}, indent=2))
    else:
        print("\n".join(format_match(results, need)))
    return 0 if usable else 1


def cmd_extend(args, root):
    from shipdesign.components import classify_extension
    model, comps = load_registry(root)
    res = classify_extension(model, comps, args.component, variant=args.variant, params=args.param or [],
                             tokens=split_tokens(args.tokens), changes_existing=args.changes_existing)
    if args.json:
        print(json.dumps(res, indent=2))
    else:
        head = {"extension": "✓ legitimate extension — no founder question needed; record it in components.yaml:",
                "founder": "✗ founder decision — ask before changing it:",
                "nothing-to-add": "✓ nothing new — reuse as-is",
                "unknown": "✗ not registered"}[res["verdict"]]
        print(head)
        for r in res["reasons"]:
            print(f"  - {r}")
        for line in res.get("snippet") or []:
            print(line)
    return 0 if res["ok"] else 1


PROJECT_MARKERS = ("project.yml", "Package.swift", "package.json", "build.gradle", "build.gradle.kts",
                   "settings.gradle", "settings.gradle.kts", ".git", "CLAUDE.md")


def cmd_adopt(args, root):
    from shipdesign.adopt import adopt
    here, up = Path(root).resolve(), Path(root).resolve().parent
    marked = lambda d: any((d / m).exists() for m in PROJECT_MARKERS) or any(d.glob("*.xcodeproj"))
    if not marked(here) and marked(up):   # drafts in a source folder can get bundled into the app
        print(f"✗ adopt: {here.name}/ looks like a source folder inside the project at {up}; "
              f"run adopt from the project root (--root {up})", file=sys.stderr)
        return 2
    platform, model, comps, notes, stats = adopt(root, args.platform, tuple(args.exclude or ()))
    out = out_path(root, args.out)
    cout = out_path(root, args.components_out)
    if out.name == "design-model.yaml" or cout.name == "components.yaml":
        print("✗ adopt only writes drafts — review, then rename them yourself", file=sys.stderr)
        return 2
    written = []
    for path, head, data in (
        (out, ["# DRAFT — generated by `design_model.py adopt` from the existing code. Review every value,",
               "# fill the TODOs (brand.feel is the founder's call), then rename to design-model.yaml.",
               "# Then: validate → emit swiftui/css to a scratch --out → diff against the old theme."], model),
        (cout, ["# DRAFT component inventory from existing code (origin: adopted). Delete entries that",
                "# are screen-specific compositions, add use_when / not_for, then rename to components.yaml."], comps),
    ):
        if path.exists() and not args.force:
            print(f"✗ {rel(path, root)} exists — re-run with --force to overwrite the draft", file=sys.stderr)
            return 1
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("\n".join(head) + "\n" + dump_yaml(data) + "\n", encoding="utf-8")
        written.append(rel(path, root))
    if args.json:
        print(json.dumps({"platform": platform, "written": written, "stats": stats, "notes": notes,
                          "components": len(comps["components"])}, indent=2))
        return 0
    print(f"✓ adopted ({platform}): " + " · ".join(f"{v} {k}" for k, v in stats.items())
          + f" · {len(comps['components'])} components")
    for w in written:
        print(f"  wrote {w}")
    ns = ((model.get("emit") or {}).get("swiftui") or {}).get("namespaces")
    if ns:
        print(f"  keeps existing names: {', '.join(f'{k} → {v}' for k, v in ns.items())}")
    ren = (((model.get("emit") or {}).get("swiftui") or (model.get("emit") or {}).get("css") or {}).get("rename"))
    if ren:
        print(f"  role renames: {', '.join(f'{k} → {v}' for k, v in ren.items())}")
    for n in notes:
        print(f"  note: {n}")
    return 0


def cmd_audit(args, root):
    from shipdesign.audit import audit, format_report
    model_path = out_path(root, args.model)
    try:
        model = load_yaml(model_path.read_text(encoding="utf-8"))
        comp_path = root / "design" / "components.yaml"
        comps = load_yaml(comp_path.read_text(encoding="utf-8")) if comp_path.exists() else None
    except (OSError, YamlError) as exc:
        print(f"✗ {exc}", file=sys.stderr)
        return 1
    rep = audit(root, model, comps, exclude=tuple(args.exclude or ()), include_token_files=args.include_token_files)
    if args.json:
        print(json.dumps(rep, indent=2))
    else:
        print(format_report(rep, args.limit))
    return 1 if args.strict and rep["total_off_scale"] else 0


def cmd_sameness(args, root):
    """Which brand-defining choices are still defaults (Ship's seed values or the platform's)."""
    from shipdesign.sameness import sameness, format_report
    try:
        model = load_yaml((root / "design-model.yaml").read_text(encoding="utf-8"))
    except OSError:
        print("No design-model.yaml — compare the app's own theme by hand: a platform accent "
              "(iOS system blue, Tailwind blue-500…), a system or very common type family, one radius on "
              "everything, motion left at Ship's seed values.")
        return 0
    except YamlError as exc:
        print(f"✗ {exc}", file=sys.stderr)
        return 1
    template_path = Path(__file__).resolve().parent.parent / "references" / "design-model-template.yaml"
    template = load_yaml(template_path.read_text(encoding="utf-8"))
    rep = sameness(model, template)
    print(json.dumps(rep, indent=2) if args.json else format_report(rep))
    return 0


def build_docs(model, comps, root):
    from shipdesign.components import emit_docs
    return generated.render("md", "docs", ["Generated by Ship from design/components.yaml + design-model.yaml — do not edit by hand."],
                            emit_docs(model, comps, root))


def cmd_docs(args, root):
    if not require_valid(root, quiet=args.check):
        return 1
    model, comps = load_registry(root)
    path = out_path(root, args.out or emit_config(model, "docs").get("out") or DOCS_DEFAULT)
    ok, st, msg, d = generated.write(path, build_docs(model, comps, root), force=args.force, check=args.check)
    report_write(path, root, ok, st, msg, d, show_diff=False)
    return 0 if ok else 1


def build_designmd(model, comps):
    from shipdesign.designmd import emit_designmd
    return generated.render("yaml", "designmd",
                            ["Generated by Ship from design-model.yaml (optional DESIGN.md-format export) — do not edit by hand."],
                            emit_designmd(model, comps), lead=["---"])


def cmd_designmd(args, root):
    if not require_valid(root, quiet=args.check):
        return 1
    model, comps = load_registry(root)
    target = args.out or emit_config(model, "designmd").get("out") or DESIGNMD_DEFAULT
    path = out_path(root, target)
    if path.name == "DESIGN.md":
        print("✗ DESIGN.md is the product's prose — export to a separate path (default design/DESIGN.spec.md)",
              file=sys.stderr)
        return 2
    ok, st, msg, d = generated.write(path, build_designmd(model, comps), force=args.force, check=args.check)
    report_write(path, root, ok, st, msg, d, show_diff=False)
    return 0 if ok else 1


def cmd_render(args, root):
    from shipdesign.preview import render_png
    if not require_valid(root, quiet=True):
        return 1
    model, comps = load_registry(root)
    schemes = ("light", "dark") if args.scheme == "both" else (args.scheme,)
    ok, msgs, written = render_png(model, comps, root, out_path(root, args.out), schemes, args.width)
    for m in msgs:
        print(f"  note: {m}" if ok else f"  {m}", file=sys.stdout if ok else sys.stderr)
    for w in written:
        print(f"✓ rendered {rel(w, root)}")
    if not ok:
        print("✗ render failed", file=sys.stderr)
    return 0 if ok else 1


# ── CLI ──────────────────────────────────────────────────────────────────────

def main(argv=None):
    ap = argparse.ArgumentParser(prog="design_model.py", description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=".", help="project root (default: cwd)")
    sub = ap.add_subparsers(dest="command", required=True)

    def common(p):
        p.add_argument("--root", default=argparse.SUPPRESS, help="project root (default: cwd)")
        return p

    p = common(sub.add_parser("validate", help="check design-model.yaml + design/components.yaml"))
    p.add_argument("--json", action="store_true")

    def emit_flags(p):
        p.add_argument("--out", help="output path (default: emit.<target>.out, else design/generated/…)")
        p.add_argument("--check", action="store_true", help="don't write; exit 1 if missing, stale or hand-edited")
        p.add_argument("--force", action="store_true", help="replace a hand-written or hand-edited file")
        p.add_argument("--dry-run", action="store_true", help="show what would change without writing")

    p = common(sub.add_parser("emit", help="generate platform files from the tokens"))
    p.add_argument("targets", nargs="+", choices=list(EMIT_TARGETS) + ["all"])
    emit_flags(p)
    for t in ("swiftui", "css", "tailwind", "compose"):
        emit_flags(common(sub.add_parser(f"emit-{t}", help=f"alias: emit {t}")))
    common(sub.add_parser("check", help="validate + every configured generated file is current (review / CI)"))
    p = common(sub.add_parser("status", help="planned vs realized components"))
    p.add_argument("--json", action="store_true")
    p = common(sub.add_parser("match", help="suitability candidates for a UI need"))
    p.add_argument("--role", required=True, help="e.g. card, button.primary, list-row")
    p.add_argument("--variant")
    p.add_argument("--tokens", help="comma-separated tokens the element needs")
    p.add_argument("--context", help="a few words about where it's used (checked against use_when / not_for)")
    p.add_argument("--json", action="store_true")
    p = common(sub.add_parser("extend", help="is adding this variant/param a legitimate extension?"))
    p.add_argument("--component", required=True)
    p.add_argument("--variant")
    p.add_argument("--param", action="append")
    p.add_argument("--tokens")
    p.add_argument("--changes-existing", action="store_true",
                   help="the change alters existing call sites' behaviour or visuals")
    p.add_argument("--json", action="store_true")
    p = common(sub.add_parser("adopt", help="draft a registry from an existing app's code"))
    p.add_argument("--platform", choices=["auto", "swiftui", "web"], default="auto")
    p.add_argument("--out", default="design-model.draft.yaml")
    p.add_argument("--components-out", default="design/components.draft.yaml")
    p.add_argument("--exclude", action="append", help="glob of paths to skip (repeatable)")
    p.add_argument("--force", action="store_true", help="overwrite existing drafts")
    p.add_argument("--json", action="store_true")
    p = common(sub.add_parser("audit", help="raw literals vs the scale + duplicated patterns"))
    p.add_argument("--model", default="design-model.yaml", help="model to audit against (e.g. the adopt draft)")
    p.add_argument("--exclude", action="append")
    p.add_argument("--include-token-files", action="store_true")
    p.add_argument("--strict", action="store_true", help="exit 1 when any off-scale literal exists")
    p.add_argument("--limit", type=int, default=15)
    p.add_argument("--json", action="store_true")
    p = common(sub.add_parser("sameness", help="brand-defining choices still at a default (evidence for the care pass)"))
    p.add_argument("--json", action="store_true")
    p = common(sub.add_parser("docs", help="generate design/COMPONENTS.md from the registry"))
    p.add_argument("--out")
    p.add_argument("--check", action="store_true")
    p.add_argument("--force", action="store_true")
    p = common(sub.add_parser("render", help="PNG of the SwiftUI preview (macOS, no simulator)"))
    p.add_argument("--out", default="design/preview/preview.png")
    p.add_argument("--scheme", choices=["light", "dark", "both"], default="light")
    p.add_argument("--width", type=float, default=430)
    p = common(sub.add_parser("emit-designmd", help="optional: export Google DESIGN.md-format tokens"))
    p.add_argument("--out")
    p.add_argument("--check", action="store_true")
    p.add_argument("--force", action="store_true")

    args = ap.parse_args(argv)
    root = Path(args.root).resolve()
    c = args.command
    if c == "validate":
        return cmd_validate(args, root)
    if c == "emit":
        return cmd_emit(args, root, args.targets)
    if c.startswith("emit-") and c != "emit-designmd":
        return cmd_emit(args, root, [c[5:]])
    return {"check": cmd_check, "status": cmd_status, "match": cmd_match, "extend": cmd_extend,
            "adopt": cmd_adopt, "audit": cmd_audit, "docs": cmd_docs, "render": cmd_render,
            "sameness": cmd_sameness,
            "emit-designmd": cmd_designmd}[c](args, root)


if __name__ == "__main__":
    sys.exit(main())
